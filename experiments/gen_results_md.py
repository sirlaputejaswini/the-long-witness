#!/usr/bin/env python3
"""Generate RESULTS.md from the run outputs in results/*.json.
No number enters RESULTS.md by hand."""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "results")


def load(name):
    return json.load(open(os.path.join(R, name)))


def main():
    e1, e2, e3, e4, e5 = (load("e1_build.json"), load("e2_verify.json"),
                          load("e3_tamper.json"), load("e4_longevity.json"),
                          load("e5_consequence.json"))
    L = []
    L.append("# Results — The Long Witness\n")
    L.append("Generated by `experiments/gen_results_md.py` from the run "
             "outputs in this folder. Every number below traces to one of "
             "those files; see `paper/NUMBERS_VERIFICATION.md` for the "
             "line-by-line mapping.\n")
    L.append("## E1 — Chain build over the HouseRules decision log\n")
    L.append(f"- Decisions chained: **{e1['records']}** (HouseRules "
             f"decision_log.jsonl, 3 scripted policies over the CASAS "
             f"Aruba recording, {e1['trace_events']} sensor events)")
    L.append(f"- Build time: **{e1['build_seconds']} s** (trace parse + "
             f"chain + anchors, single thread)")
    L.append(f"- Ledger size: **{e1['ledger_bytes']} bytes** vs source "
             f"decision log {e1['source_decision_log_bytes']} bytes — "
             f"**{e1['overhead_pct']}% overhead**, "
             f"{e1['bytes_per_record']} bytes per record\n")
    L.append("## E2 — Independent verification (tools/verify.py)\n")
    L.append(f"- Clean ledger verdict: **ok = {e2['verdict']['ok']}**, "
             f"{e2['verdict']['records']} records")
    L.append(f"- Full-chain verify time: **{e2['verify_seconds_reported']} s** "
             f"(wall {e2['wall_seconds']} s), i.e. "
             f"**{e2['per_10000_records_seconds']} s per 10,000 records**\n")
    L.append("## E3 — Tamper battery (seeded, seed 20261103)\n")
    L.append("| tamper class | cases | detected | missed | detection rate |")
    L.append("|---|---|---|---|---|")
    for cls, s in e3["per_class"].items():
        L.append(f"| {cls} | {s['cases']} | {s['detected']} | {s['missed']} "
                 f"| {s['detection_rate']} |")
    L.append(f"\nTotal cases: **{e3['total_cases']}**. The "
             "`truncate_and_reforge_trailer` class is the blind spot, "
             "and it is reported, not hidden: a chain shortened by an "
             "attacker who also recomputes a consistent trailer is "
             "internally valid, and only an externally published chain "
             "hash (or a countersignature from a second witness) detects "
             "it. That limit is stated in SPEC.md §8 and in the paper.\n")
    L.append("## E4 — Longevity drill (spec-only reimplementation)\n")
    L.append(f"- Minimal reader written from SPEC.md only "
             f"(tools/mini_reader.py), no shared code, no trace")
    L.append(f"- Clean-ledger verdict: **ok = {e4['clean_ledger_mini_ok']}**")
    L.append(f"- Agreement with the full verifier across "
             f"{e4['cases_compared']} tampered variants: "
             f"**{e4['agreements']} agreements, agreement rate "
             f"{e4['agreement_rate']}**\n")
    L.append("## E5 — Consequence check (does the world show it?)\n")
    L.append(f"Executed records: {e5['executed_records']}. Scored for a "
             f"positive sensor signature: {e5['scored']}; matched: "
             f"{e5['matched']} — **overall match rate "
             f"{e5['overall_match_rate']}**. "
             f"{e5['no_sensor_signature_excluded']} executed records "
             f"(alarm silencing/disabling) have no CASAS sensor signature "
             f"and were excluded from scoring, never counted as matches "
             f"or misses.\n")
    L.append("| check | checked | matched | rate |")
    L.append("|---|---|---|---|")
    for name, g in e5["groups"].items():
        L.append(f"| {name} | {g['checked']} | {g['matched']} | "
                 f"{g['match_rate']} |")
    fd = e5["groups"]["front_door (any door-sensor event, following 10 min)"]
    L.append(f"\nFront-door sensitivity: forward window "
             f"{fd['match_rate']}, preceding window "
             f"{fd['match_rate_preceding']}, symmetric ±10 min "
             f"{fd['match_rate_symmetric']}. Door decisions in this log "
             f"are dominated by scheduled locks and lockups, which are "
             f"not physical door movements — the forward-window rate is "
             f"the honest headline and it is weak.\n")
    for name, g in e5["absence_signature_groups"].items():
        L.append(f"Absence signature — {name}: checked {g['checked']}, "
                 f"windows empty of living-zone motion "
                 f"{g['window_empty_of_living_motion']}, resident away "
                 f"{g['resident_away']}. The executed feed-shares happened "
                 f"while the resident was out; the anchor's evidence is "
                 f"the empty house itself.\n")
    with open(os.path.join(ROOT, "RESULTS.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("RESULTS.md written")


if __name__ == "__main__":
    main()
